def apply_formatting(path: Path) -> None:
    wb = load_workbook(path)
    for ws in wb.worksheets:
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions
        for cell in ws[1]:
            cell.font = HEADER_FONT
            cell.fill = HEADER_FILL
            cell.alignment = Alignment(horizontal="center", vertical="center")
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                cell.font = BODY_FONT
                cell.alignment = Alignment(vertical="top", wrap_text=True)
        for col in ws.columns:
            letter = col[0].column_letter
            max_len = max(len(str(cell.value)) if cell.value is not None else 0 for cell in col)
            ws.column_dimensions[letter].width = min(max(max_len + 2, 10), 42)

    summary_ws = wb["板块总览"]
    summary_ws["A1"].fill = TITLE_FILL
    summary_ws["B1"].fill = TITLE_FILL
    summary_ws["C1"].fill = TITLE_FILL
    summary_ws["D1"].fill = TITLE_FILL
    summary_ws["E1"].fill = TITLE_FILL
    summary_ws["F1"].fill = TITLE_FILL
    summary_ws["G1"].fill = TITLE_FILL
    for cell in summary_ws[1]:
        cell.font = TITLE_FONT

    wb.save(path)


def main() -> int:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    sector_df = build_sector_overview()
    stock_df = build_stock_list()
    notes_df = build_notes()

    with pd.ExcelWriter(OUTPUT_PATH, engine="openpyxl") as writer:
        sector_df.to_excel(writer, sheet_name="板块总览", index=False)
        stock_df.to_excel(writer, sheet_name="个股清单", index=False)
        notes_df.to_excel(writer, sheet_name="使用说明", index=False)

    apply_formatting(OUTPUT_PATH)
    print(f"已生成: {OUTPUT_PATH.resolve()}")
    print(f"板块数: {len(sector_df)}")
    print(f"个股数: {len(stock_df)}")
    return 0


